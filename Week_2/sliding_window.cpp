#include <bits/stdc++.h>

using namespace std;

int main(){
    vector<int> a = { 0,   // a[0] chỉ để đệm, không dùng
     3,  7,  0, 12,  5,  9,  1,  4, 15,  2,   // a[1..10]
     8,  6, 11,  0,  3, 14,  7,  2, 10,  5,   // a[11..20]
     1,  9, 13,  4,  0,  6, 18,  3,  7,  2,   // a[21..30]
     5, 11,  8,  1, 16,  4,  9,  0, 12,  6,   // a[31..40]
     2,  7,  3, 19,  5, 10,  1,  8,  4, 13,   // a[41..50]
     0,  6,  9,  2, 15,  7,  3, 11,  5,  1,   // a[51..60]
    14,  4,  8,  0, 10,  2, 17,  6,  3,  9,   // a[61..70]
     7,  1, 12,  5,  0,  8,  4, 20,  2, 11,   // a[71..80]
     6,  3,  9, 13,  1,  7,  5,  0, 16,  4,   // a[81..90]
    10,  2,  8,  6, 14,  3,  0,  9,  5, 12    // a[91..100]
    };

    int n=100;

    int res = 0;
    int cur = 0; 
    int sum;
    cin >> sum;

    int l=1;
    for (int r=1; r<=n; r++){
        cur += a[r];
        while (cur >= sum){
            cur -= a[l];
            l++;
        }
        res = max(res, r-l+1);
    }

    cout << res;
}